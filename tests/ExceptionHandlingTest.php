<?php
declare(strict_types=1);

use Mtphp\Testing\Assert;
use Mtphp\Testing\TestCase;
use Mtphp\Exception\ApiException;
use Mtphp\Exception\HttpException;
use Mtphp\Http\Request;
use Mtphp\Http\Response;
use Mtphp\Http\Middleware\HealthCheck;
use Mtphp\Log\Logger;
use Mtphp\App;

/**
 * 统一异常 / 健康检查 / 请求ID / 结构化日志 的集成测试
 */
class ExceptionHandlingTest extends TestCase
{
    private string $tmp;

    protected function setUp(): void
    {
        $this->tmp = sys_get_temp_dir() . '/mtphp_exc_' . uniqid('', true);
        mkdir($this->tmp, 0755, true);
        HealthCheck::reset();
    }

    protected function tearDown(): void
    {
        HealthCheck::reset();
        Logger::setRequestId(null);
        $this->rmdir($this->tmp);
    }

    private function rmdir(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }
        $items = scandir($dir) ?: [];
        foreach ($items as $it) {
            if ($it === '.' || $it === '..') {
                continue;
            }
            $p = $dir . '/' . $it;
            is_dir($p) ? $this->rmdir($p) : @unlink($p);
        }
        @rmdir($dir);
    }

    // ---------- 1. ApiException ----------
    public function testApiExceptionFields(): void
    {
        $e = new ApiException('余额不足', 4001, 400, ['need' => 100]);
        Assert::assertSame(4001, $e->getBusinessCode());
        Assert::assertSame(400, $e->getStatusCode());
        Assert::assertSame(['need' => 100], $e->getData());
        Assert::assertSame('余额不足', $e->getMessage());

        // 默认业务码回退为 HTTP 状态码
        $e2 = new ApiException('x', 0, 409);
        Assert::assertSame(409, $e2->getBusinessCode());
    }

    // ---------- 2. 健康检查中间件 ----------
    public function testHealthzLiveness(): void
    {
        $req = $this->capturePath('/healthz');
        $mw  = new HealthCheck();
        $resp = $mw->handle($req, fn() => new Response('should-not-reach', 200));
        Assert::assertSame(200, $resp->getStatus());
        $body = json_decode((string) $resp->getBody(), true);
        Assert::assertSame('ok', $body['status']);
    }

    public function testReadyReadinessOk(): void
    {
        HealthCheck::check('app', fn() => true);
        HealthCheck::check('cache', fn() => ['ok' => true, 'detail' => 'hit']);
        $req  = $this->capturePath('/ready');
        $resp = (new HealthCheck())->handle($req, fn() => new Response('x'));
        Assert::assertSame(200, $resp->getStatus());
        $body = json_decode((string) $resp->getBody(), true);
        Assert::assertSame('ready', $body['status']);
        Assert::assertSame(true, $body['checks']['app']['ok']);
        Assert::assertSame('hit', $body['checks']['cache']['detail']);
    }

    public function testReadyReadinessFail(): void
    {
        HealthCheck::check('db', fn() => ['ok' => false, 'error' => 'down']);
        $req  = $this->capturePath('/ready');
        $resp = (new HealthCheck())->handle($req, fn() => new Response('x'));
        Assert::assertSame(503, $resp->getStatus());
        $body = json_decode((string) $resp->getBody(), true);
        Assert::assertSame('not_ready', $body['status']);
        Assert::assertSame('down', $body['checks']['db']['error']);
    }

    public function testHealthCheckPassesThroughNormalPath(): void
    {
        $req  = $this->capturePath('/api/user/1');
        $mw   = new HealthCheck();
        $resp = $mw->handle($req, fn() => new Response('reached', 201));
        Assert::assertSame(201, $resp->getStatus());
        Assert::assertSame('reached', (string) $resp->getBody());
    }

    // ---------- 3. 请求 ID ----------
    public function testRequestIdFromHeader(): void
    {
        $_SERVER['HTTP_X_REQUEST_ID'] = 'upstream-123';
        $req = Request::capture();
        Assert::assertSame('upstream-123', $req->requestId());
    }

    public function testRequestIdAutoGenerated(): void
    {
        $req = $this->capturePath('/x');
        $id  = $req->requestId();
        Assert::assertTrue(is_string($id) && $id !== '');
        // 幂等
        Assert::assertSame($id, $req->requestId());
    }

    // ---------- 4. 结构化日志 (JSON) ----------
    public function testJsonStructuredLogIncludesRequestId(): void
    {
        $file = $this->tmp . '/json.log';
        $log  = new Logger($file, 'debug', 'json');
        Logger::setRequestId('req-xyz');
        $log->error('boom', ['order_id' => 9]);

        $lines = file($file);
        Assert::assertTrue(is_array($lines) && count($lines) === 1);
        $rec = json_decode($lines[0], true);
        Assert::assertSame('req-xyz', $rec['request_id']);
        Assert::assertSame('ERROR', $rec['level']);
        Assert::assertSame('boom', $rec['msg']);
        Assert::assertSame(9, $rec['context']['order_id']);
        Assert::assertTrue(isset($rec['ts']));
    }

    public function testJsonLogThrowableContext(): void
    {
        $file = $this->tmp . '/json2.log';
        $log  = new Logger($file, 'debug', 'json');
        Logger::setRequestId(null);
        $log->warning('oops', new \RuntimeException('bad thing', 42));
        $rec = json_decode(file_get_contents($file), true);
        Assert::assertSame('RuntimeException', $rec['context']['exception']);
        Assert::assertSame('bad thing', $rec['context']['message']);
        Assert::assertTrue(str_contains($rec['context']['file'], 'ExceptionHandlingTest.php'));
    }

    public function testTextLogBackwardCompatible(): void
    {
        $file = $this->tmp . '/text.log';
        $log  = new Logger($file, 'debug', 'text');
        $log->info('hello', ['a' => 1]);
        $line = rtrim(file_get_contents($file));
        Assert::assertTrue(str_starts_with($line, '[') && str_contains($line, 'INFO: hello'));
    }

    // ---------- 5. App 统一错误渲染 ----------
    public function testAppRendersApiExceptionEnvelope(): void
    {
        $app = $this->makeApp();
        $this->setAppRequest($app, '/api/x', true);
        $resp = $this->callToErrorResponse($app, new ApiException('余额不足', 4001, 400, ['need' => 100]));
        Assert::assertSame(400, $resp->getStatus());
        $body = json_decode((string) $resp->getBody(), true);
        Assert::assertSame(4001, $body['code']);
        Assert::assertSame('余额不足', $body['message']);
        Assert::assertSame(['need' => 100], $body['data']);
        Assert::assertTrue(isset($body['request_id']));
    }

    public function testAppRendersValidation422Envelope(): void
    {
        $app = $this->makeApp();
        $this->setAppRequest($app, '/api/reg', true);
        $ve  = new \Mtphp\Validation\ValidationException(['name' => ['必填']]);
        $resp = $this->callToErrorResponse($app, $ve);
        Assert::assertSame(422, $resp->getStatus());
        $body = json_decode((string) $resp->getBody(), true);
        Assert::assertSame(422, $body['code']);
        Assert::assertSame(['name' => ['必填']], $body['data']['errors']);
    }

    public function testAppRendersGenericJsonForApi(): void
    {
        $app = $this->makeApp();
        $this->setAppRequest($app, '/api/missing', true);
        $resp = $this->callToErrorResponse($app, new HttpException(404, 'gone'));
        Assert::assertSame(404, $resp->getStatus());
        $body = json_decode((string) $resp->getBody(), true);
        Assert::assertSame(404, $body['code']);
        Assert::assertSame('Not Found', $body['message']);
    }

    public function testAppRendersHtmlForNonApi(): void
    {
        $app = $this->makeApp();
        $this->setAppRequest($app, '/page', false);
        $resp = $this->callToErrorResponse($app, new HttpException(404, 'gone'));
        Assert::assertSame(404, $resp->getStatus());
        $ct = $resp->getHeaders()['Content-Type'] ?? '';
        Assert::assertTrue(str_contains($ct, 'text/html'));
    }

    // ---------- 测试辅助 ----------

    private function capturePath(string $path): Request
    {
        $_SERVER['REQUEST_METHOD'] = 'GET';
        $_SERVER['REQUEST_URI']    = $path;
        unset($_SERVER['HTTP_X_REQUEST_ID'], $_SERVER['HTTP_ACCEPT'], $_SERVER['CONTENT_TYPE']);
        return Request::capture();
    }

    private function makeApp(): App
    {
        $root = $this->tmp . '/approot';
        mkdir($root . '/config', 0755, true);
        // 复制真实 config 以保证 Config 扫描不缺文件
        foreach (glob('/d/www/mtphp/config/*.php') as $src) {
            copy($src, $root . '/config/' . basename($src));
        }
        // 覆写为测试友好的最小配置（关闭探针以避免在 App 构造期注册 db 检查）
        file_put_contents($root . '/config/app.php', "<?php return [\n"
            . "  'name' => 't', 'timezone' => 'Asia/Shanghai', 'debug' => false,\n"
            . "  'health_probe' => false, 'middleware' => [],\n"
            . "  'security' => ['headers' => false, 'csrf' => false, 'cors' => false],\n"
            . "];");
        return new App($root);
    }

    private function setAppRequest(App $app, string $path, bool $json): void
    {
        $req = $this->capturePath($path);
        if ($json) {
            $req->header('accept'); // no-op to keep typing simple
            $_SERVER['HTTP_ACCEPT'] = 'application/json';
            $req = Request::capture(); // 重新捕获以带上 Accept
        }
        $rp = new \ReflectionProperty($app, 'currentRequest');
        $rp->setAccessible(true);
        $rp->setValue($app, $req);
        $rid = new \ReflectionProperty($app, 'requestId');
        $rid->setAccessible(true);
        $rid->setValue($app, $req->requestId());
    }

    private function callToErrorResponse(App $app, \Throwable $e): Response
    {
        $m = new \ReflectionMethod($app, 'toErrorResponse');
        $m->setAccessible(true);
        return $m->invoke($app, $e);
    }
}
